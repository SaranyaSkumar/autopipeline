import fs from "node:fs/promises";
import path from "node:path";
const supported=["node","python","java"];
const read=async(root,file)=>fs.readFile(path.join(root,file),"utf8").catch(e=>{if(e.code==="ENOENT")return null;throw e});
export async function detect(root){
 const pkg=await read(root,"package.json");
 if(pkg){const p=JSON.parse(pkg);return {language:"node",manager:await read(root,"pnpm-lock.yaml")?"pnpm":await read(root,"yarn.lock")?"yarn":"npm",scripts:p.scripts||{}}}
 if(await read(root,"pyproject.toml"))return {language:"python",scripts:{}};
 if(await read(root,"pom.xml"))return {language:"java",scripts:{}};
 throw Error("Unsupported project: expected package.json, pyproject.toml or pom.xml");
}
export function suggest(d){
 const c={version:1,project:{language:d.language},ci:{lint:false,typecheck:false,unit:false,build:false,e2e:false,dependencyAudit:false},deploy:{enabled:false}};
 if(d.language==="node"){c.project.packageManager=d.manager;for(const [k,v] of Object.entries({lint:"lint",typecheck:"typecheck",unit:"test",build:"build",e2e:"test:e2e"}))c.ci[k]=!!d.scripts[v];c.ci.dependencyAudit=d.manager==="npm";}
 else c.ci.unit=true;
 return c;
}
export function render(c,d){
 if(!c||c.version!==1||!supported.includes(c.project?.language)||!c.ci)throw Error("Invalid AutoPipeline config");
 if(d&&d.language!==c.project.language)throw Error("Detected language differs from config");
 if(c.deploy?.enabled)throw Error("Deployment is not supported in v0.1");
 for(const k of ["lint","typecheck","unit","build","e2e","dependencyAudit"])if(c.ci[k]!==undefined&&typeof c.ci[k]!=="boolean")throw Error("Expected boolean: "+k);
 const language=c.project.language,manager=c.project.packageManager||d?.manager||"npm";
 if(language==="node"&&!["npm","pnpm","yarn"].includes(manager))throw Error("Unsupported package manager");
 if(language==="node"&&c.ci.dependencyAudit&&manager!=="npm")throw Error("Audit only supports npm in v0.1");
 const lines=["# Generated by AutoPipeline. Edit autopipeline.json and regenerate.","name: AutoPipeline CI","on:","  pull_request:","  push:","    branches: [main]","permissions:","  contents: read","jobs:","  ci:","    runs-on: ubuntu-latest","    timeout-minutes: 30","    steps:","      - name: Checkout","        uses: actions/checkout@11bd71901bbe5b1630ceea73d27597364c9af683 # v4.2.2"];
 const step=(label,command)=>{if(typeof command!=="string"||!command.trim()||/[\r\n\0]/.test(command))throw Error("Invalid command: "+label);lines.push("      - name: "+label,"        run: "+JSON.stringify(command));};
 const cmds=c.ci.commands||{};
 if(language==="node"){
   const runtime=String(c.project.runtime||"22");if(!["20","22","24"].includes(runtime))throw Error("Unsupported Node runtime");
   lines.push("      - name: Setup Node","        uses: actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4.4.0","        with:","          node-version: '"+runtime+"'","          cache: "+manager);
   if(manager!=="npm")step("Enable corepack","corepack enable");
   step("Install",manager==="npm"?"npm ci":manager==="pnpm"?"pnpm install --frozen-lockfile":"yarn install --immutable");
   for(const [key,label,script] of [["lint","Lint","lint"],["typecheck","Typecheck","typecheck"],["unit","Unit tests","test"],["build","Build","build"],["e2e","E2E tests","test:e2e"]]){
     if(!c.ci[key])continue;
     if(d&&!d.scripts?.[script]&&!cmds[key])throw Error("Missing script: "+script);
     step(label,cmds[key]||(manager==="npm"?"npm run "+script:manager+" "+script));
   }
   if(c.ci.dependencyAudit)step("Dependency audit","npm audit --audit-level=high");
 }else if(language==="python"){
   const runtime=String(c.project.runtime||"3.12");if(!/^3\.(10|11|12|13)$/.test(runtime))throw Error("Unsupported Python runtime");
   lines.push("      - name: Setup Python","        uses: actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065 # v5.6.0","        with:","          python-version: '"+runtime+"'");
   step("Install","python -m pip install -e . pytest ruff pip-audit");
   for(const [key,label,defaultCmd] of [["lint","Lint","ruff check ."],["typecheck","Typecheck","python -m compileall ."],["unit","Unit tests","pytest"],["build","Build","python -m build"],["e2e","E2E tests","pytest tests/e2e"]])if(c.ci[key])step(label,cmds[key]||defaultCmd);
   if(c.ci.dependencyAudit)step("Dependency audit","pip-audit");
 }else{
   const runtime=String(c.project.runtime||"21");if(!["17","21","25"].includes(runtime))throw Error("Unsupported JDK");
   lines.push("      - name: Setup Java","        uses: actions/setup-java@dded0888837ed1f317902acf8a20df0ad188d165 # v4.7.1","        with:","          distribution: 'temurin'","          java-version: '"+runtime+"'");
   for(const [key,label,defaultCmd] of [["lint","Lint","./mvnw -B checkstyle:check"],["typecheck","Typecheck","./mvnw -B compile"],["unit","Unit tests","./mvnw -B test"],["build","Build","./mvnw -B package -DskipTests"],["e2e","E2E tests","./mvnw -B verify"]])if(c.ci[key])step(label,cmds[key]||defaultCmd);
   if(c.ci.dependencyAudit)throw Error("Java audit adapter is not available");
 }
 if(!Object.entries(c.ci).some(([k,v])=>k!=="commands"&&v===true))throw Error("Enable at least one check");
 return lines.join("\n")+"\n";
}
export async function run(args,root=process.cwd()){
 const command=args[0],d=await detect(root);
 if(command==="init"){if(await read(root,"autopipeline.json"))throw Error("Config already exists");await fs.writeFile(path.join(root,"autopipeline.json"),JSON.stringify(suggest(d),null,2)+"\n");return "Created autopipeline.json";}
 const raw=await read(root,"autopipeline.json");if(!raw)throw Error("Run autopipeline init first");
 const config=JSON.parse(raw),output=render(config,d),target=".github/workflows/autopipeline.yml";
 if(command==="doctor")return "Valid "+d.language+" pipeline";
 if(command==="render")return output;
 if(command==="check"){if(await read(root,target)!==output)throw Error("Workflow has drifted; regenerate");return "Workflow matches configuration";}
 if(command==="generate"){if(await read(root,target)&&!args.includes("--force"))throw Error("Workflow exists: use --force");await fs.mkdir(path.dirname(path.join(root,target)),{recursive:true});await fs.writeFile(path.join(root,target),output);return "Generated "+target;}
 throw Error("Usage: autopipeline init|doctor|render|generate|check [--force]");
}
